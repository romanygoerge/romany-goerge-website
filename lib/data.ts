// Helper functions for easy querying
export function getAllVideos(): Video[] {
  return [SPOTLIGHT_VIDEO, ...VIDEOS];
}

export function getVideoBySlugOrId(identifier: string): Video | undefined {
  const all = getAllVideos();
  return all.find((v) => v.slug === identifier || v.id === identifier || v.youtubeId === identifier);
}

export function getVideosByCategory(category: CategoryKey): Video[] {
  return getAllVideos().filter((v) => v.category === category);
}

export function getCategoryInfo(categoryKey: string): CategoryInfo | undefined {
  return CATEGORIES.find((c) => c.key === categoryKey);
}
